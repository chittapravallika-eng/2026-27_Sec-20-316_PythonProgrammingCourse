s = set(map(int, input("Enter set elements: ").split()))
print("Set:", s)
x = int(input("Enter element to search: "))
print("Membership:", x in s)
a = int(input("Enter element to add: "))
s.add(a)
print("After add:", s)
r = int(input("Enter element to remove: "))
s.remove(r)
print("After remove:", s)
d = int(input("Enter element to discard: "))
s.discard(d)
print("After discard:", s)